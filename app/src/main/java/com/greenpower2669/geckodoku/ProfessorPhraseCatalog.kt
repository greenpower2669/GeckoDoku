    private fun phrase(
        id: String,
        text: String,
        category: PhraseCategory
    ): ProfessorPhrase =
        ProfessorPhrase(
            id = id,
            text = text,
            category = category,
            rarity =
                when (category) {
                    PhraseCategory.RARE ->
                        PhraseRarity.RARE
                    PhraseCategory.FAB ->
                        PhraseRarity.SEMI_RARE
                    else ->
                        PhraseRarity.NORMAL
                },
            moods = moodsFor(category)
        )

    private fun legacyCategory(
        number: Int
    ): PhraseCategory =
        when (number) {
            in 1..20 ->
                PhraseCategory.HESITATION
            in 21..40 ->
                PhraseCategory.ABSURD
            else ->
                PhraseCategory.GENERAL
        }

    private fun moodsFor(
        category: PhraseCategory
    ): Set<ProfessorMood> =
        when (category) {
            PhraseCategory.GENERAL ->
                setOf(
                    ProfessorMood.NEUTRAL,
                    ProfessorMood.CURIOUS
                )
            PhraseCategory.SUCCESS ->
                setOf(
                    ProfessorMood.PROUD,
                    ProfessorMood.ENCOURAGING
                )
            PhraseCategory.ERROR ->
                setOf(
                    ProfessorMood.ENCOURAGING,
                    ProfessorMood.PEDAGOGICAL
                )
            PhraseCategory.STREAK ->
                setOf(
                    ProfessorMood.IMPRESSED,
                    ProfessorMood.PROUD
                )
            PhraseCategory.HESITATION ->
                setOf(
                    ProfessorMood.PEDAGOGICAL,
                    ProfessorMood.CURIOUS,
                    ProfessorMood.ENCOURAGING
                )
            PhraseCategory.ABSURD,
            PhraseCategory.SELF ->
                setOf(
                    ProfessorMood.NEUTRAL,
                    ProfessorMood.TAQUIN
                )
            PhraseCategory.SMART ->
                setOf(ProfessorMood.IMPRESSED)
            PhraseCategory.FINISH ->
                setOf(
                    ProfessorMood.PROUD,
                    ProfessorMood.IMPRESSED
                )
            PhraseCategory.RETURN ->
                setOf(
                    ProfessorMood.CURIOUS,
                    ProfessorMood.NEUTRAL
                )
            PhraseCategory.RARE ->
                ProfessorMood.entries.toSet()
            PhraseCategory.FAB ->
                setOf(
                    ProfessorMood.NEUTRAL,
                    ProfessorMood.TAQUIN,
                    ProfessorMood.CURIOUS
                )
            PhraseCategory.TAQUIN ->
                setOf(ProfessorMood.TAQUIN)
        }
