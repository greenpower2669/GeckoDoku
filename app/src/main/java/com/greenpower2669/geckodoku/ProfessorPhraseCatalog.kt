    fun normalizeText(text: String): String =
        text
            .lowercase(Locale.ROOT)
            .replace(
                Regex("""[\p{P}\p{S}]+"""),
                " "
            )
            .trim()
            .replace(
                Regex("""\s+"""),
                " "
            )

    fun textSimilarity(
        first: String,
        second: String
    ): Double {
        val a =
            normalizeText(first)
                .split(" ")
                .filter { it.isNotBlank() }
                .toSet()
        val b =
            normalizeText(second)
                .split(" ")
                .filter { it.isNotBlank() }
                .toSet()

        if (a.isEmpty() && b.isEmpty()) {
            return 1.0
        }

        val union = a union b
        if (union.isEmpty()) {
            return 0.0
        }

        return (a intersect b).size.toDouble() /
            union.size.toDouble()
    }

    fun nearDuplicatePairs(
        threshold: Double = 0.72
    ): List<Pair<String, String>> {
        val result =
            mutableListOf<Pair<String, String>>()

        for (firstIndex in 0 until all.lastIndex) {
            for (
                secondIndex in
                firstIndex + 1 until all.size
            ) {
                val first = all[firstIndex]
                val second = all[secondIndex]
                if (
                    textSimilarity(
                        first.text,
                        second.text
                    ) >= threshold
                ) {
                    result += first.id to second.id
                }
            }
        }

        return result
    }

